"""Thin client over any OpenAI-compatible chat completions endpoint (Groq by default).

Retries on 429 and 5xx are handled by the SDK (`max_retries`), which waits as long as the `retry-after` header asks.
This module only converts SDK objects into plain dataclasses and SDK errors into `LlmError`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Literal, Protocol

import openai
from openai import OpenAI

from plm.agent.config import AgentConfig

Message = dict[str, Any]


class LlmError(RuntimeError):
    pass


class LlmRateLimitError(LlmError):
    pass


class LlmToolCallError(LlmError):
    """The provider rejected a malformed tool call generated by the model (Groq: HTTP 400 `tool_use_failed`)."""


@dataclass(frozen=True, slots=True)
class ToolCall:
    id: str
    name: str
    arguments: str


@dataclass(frozen=True, slots=True)
class Usage:
    prompt_tokens: int
    completion_tokens: int


@dataclass(frozen=True, slots=True)
class LlmMessage:
    content: str | None
    tool_calls: tuple[ToolCall, ...]
    usage: Usage | None = None

    def to_message(self) -> Message:
        """The assistant message to append to the conversation before the tool results."""
        message: Message = {"role": "assistant", "content": self.content}
        if self.tool_calls:
            message["tool_calls"] = [
                {"id": call.id, "type": "function", "function": {"name": call.name, "arguments": call.arguments}}
                for call in self.tool_calls
            ]
        return message


class LlmClient(Protocol):
    def complete(
        self,
        messages: list[Message],
        tools: list[Message] | None = None,
        tool_choice: Literal["auto", "none"] = "auto",
    ) -> LlmMessage: ...


class OpenAiCompatibleClient:
    """Implements `LlmClient`. `client` can be injected for tests."""

    def __init__(self, config: AgentConfig, client: OpenAI | None = None) -> None:
        self._config = config
        self._client = client or OpenAI(
            api_key=config.api_key,
            base_url=config.base_url,
            timeout=config.timeout_s,
            max_retries=config.max_retries,
        )

    def complete(
        self,
        messages: list[Message],
        tools: list[Message] | None = None,
        tool_choice: Literal["auto", "none"] = "auto",
    ) -> LlmMessage:
        options: dict[str, Any] = {"tools": tools, "tool_choice": tool_choice} if tools else {}
        where = f"{self._config.model} at {self._config.base_url}"
        try:
            response = self._client.chat.completions.create(
                model=self._config.model,
                messages=messages,
                temperature=self._config.temperature,
                **options,
            )
        except openai.RateLimitError as exc:
            raise LlmRateLimitError(f"Rate limit reached on {where}: {exc.message}") from exc
        except openai.APIStatusError as exc:
            if exc.status_code == 400 and (
                exc.code == "tool_use_failed" or "tool call validation" in exc.message.lower()
            ):
                raise LlmToolCallError(f"Malformed tool call rejected by {where}: {exc.message}") from exc
            raise LlmError(f"HTTP {exc.status_code} from {where}: {exc.message}") from exc
        except openai.APIConnectionError as exc:
            raise LlmError(f"Cannot reach {where}: {exc}") from exc

        if not response.choices:
            raise LlmError(f"Empty response from {where}")
        message = response.choices[0].message
        tool_calls = tuple(
            ToolCall(id=call.id, name=call.function.name, arguments=call.function.arguments or "{}")
            for call in message.tool_calls or ()
            if call.type == "function"
        )
        usage = (
            Usage(prompt_tokens=response.usage.prompt_tokens, completion_tokens=response.usage.completion_tokens)
            if response.usage
            else None
        )
        return LlmMessage(content=message.content, tool_calls=tool_calls, usage=usage)
